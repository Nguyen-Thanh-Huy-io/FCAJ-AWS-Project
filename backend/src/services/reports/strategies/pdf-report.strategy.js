const ReportGeneratorStrategy = require('./report-generator.strategy');

class PdfReportStrategy extends ReportGeneratorStrategy {
  async generate(title, brand, data, options = {}) {
    const brandName = brand?.name || 'PubliCast Brand';
    const logoText = options.isWhiteLabel ? `White-label (Logo: ${options.brandLogoUrl || 'Default'})` : 'Powered by PubliCast';
    const colorHex = options.brandColorHex || '#3B82F6';
    
    // Xây dựng nội dung text hiển thị trong PDF
    let content = `
============================================================
BRAND ANALYTICS REPORT: ${title.toUpperCase()}
============================================================
Brand: ${brandName}
Created Date: ${new Date().toLocaleDateString('vi-VN')}
Theme Color: ${colorHex}
Branding: ${logoText}

------------------------------------------------------------
1. GENERAL PERFORMANCE OVERVIEW
------------------------------------------------------------
Total Reach: ${data.overview?.reach?.toLocaleString() || 0}
Total Impressions: ${data.overview?.impressions?.toLocaleString() || 0}
Total Engagements: ${data.overview?.engagements?.toLocaleString() || 0}
Engagement Rate (AVG): ${data.overview?.engagementRate?.toFixed(2) || '0.00'}%

------------------------------------------------------------
2. CHANNEL DETAILED ANALYTICS
------------------------------------------------------------
`;
    
    if (data.channels && data.channels.length > 0) {
      data.channels.forEach(ch => {
        content += `
Platform: ${ch.platform} (${ch.displayName})
- Followers: ${ch.followers?.toLocaleString() || 0}
- Posts: ${ch.postsCount || 0}
- Engagement Rate: ${ch.engagementRate?.toFixed(2) || '0.00'}%
`;
      });
    } else {
      content += `
No active channel data linked for this report period.
`;
    }
    
    content += `
------------------------------------------------------------
3. TOP VIRAL POSTS
------------------------------------------------------------
`;
    
    if (data.topPosts && data.topPosts.length > 0) {
      data.topPosts.forEach((post, idx) => {
        content += `
[#${idx + 1}] Platform: ${post.platform}
- Title/Caption: ${post.title || post.caption || 'No Title'}
- Likes: ${post.likes || 0} | Comments: ${post.comments || 0} | Shares: ${post.shares || 0}
- Engagement Rate: ${post.engagementRate || '0.0'}%
`;
      });
    } else {
      content += `
No posts found in the analytics range.
`;
    }
    
    content += `
============================================================
Generated by PubliCast - Automated Analytics Platform
============================================================
`;

    const lines = content.split('\n');
    let pdfStream = 'BT\n/F1 9 Tf\n12 TL\n50 800 Td\n';
    
    lines.forEach(line => {
      const escapedLine = line.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
      const asciiLine = removeVietnameseTones(escapedLine);
      pdfStream += `(${asciiLine}) Tj T*\n`;
    });
    
    pdfStream += 'ET\n';
    
    const streamLength = Buffer.byteLength(pdfStream);
    
    const pdfData = 
`%%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>
endobj
4 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>
endobj
5 0 obj
<< /Length ${streamLength} >>
stream
${pdfStream}endstream
endobj
xref
0 6
0000000000 65535 f 
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
0000000222 00000 n 
0000000293 00000 n 
trailer
<< /Size 6 /Root 1 0 R >>
startxref
${308 + streamLength}
%%%%EOF
`;

    return {
      buffer: Buffer.from(pdfData, 'utf-8'),
      contentType: 'application/pdf',
      extension: 'pdf'
    };
  }
}

function removeVietnameseTones(str) {
  str = str.replace(/à|á|ạ|ả|ã|â|ầ|ấ|ậ|ẩ|ẫ|ă|ằ|ắ|ặ|ẳ|ẵ/g,"a"); 
  str = str.replace(/è|é|ẹ|ẻ|ẽ|ê|ề|ế|ệ|ể|ễ/g,"e"); 
  str = str.replace(/ì|í|ị|ỉ|ĩ/g,"i"); 
  str = str.replace(/ò|ó|ọ|ỏ|õ|ô|ồ|ố|ộ|ổ|ỗ|ơ|ờ|ớ|ợ|ở|ỡ/g,"o"); 
  str = str.replace(/ù|ú|ụ|ủ|ũ|ư|ừ|ứ|ự|ử|ữ/g,"u"); 
  str = str.replace(/ỳ|ý|ỵ|ỷ|ỹ/g,"y"); 
  str = str.replace(/đ/g,"d");
  str = str.replace(/À|Á|Ạ|Ả|Ã|Â|Ầ|Ấ|Ậ|Ẩ|Ẫ|Ă|Ằ|Ắ|Ặ|Ẳ|Ẵ/g, "A");
  str = str.replace(/È|É|Ẹ|Ẻ|Ẽ|Ê|Ề|Ế|Ệ|Ể|Ễ/g, "E");
  str = str.replace(/Ì|Í|Ị|Ỉ|Ĩ/g, "I");
  str = str.replace(/Ò|Ó|Ọ|Ỏ|Õ|Ô|Ồ|Ố|Ộ|Ổ|Ỗ|Ơ|Ờ|Ớ|Ợ|Ở|Ỡ/g, "O");
  str = str.replace(/Ù|Ú|Ụ|Ủ|Ũ|Ư|Ừ|Ứ|Ự|Ử|Ữ/g, "U");
  str = str.replace(/Ỳ|Ý|Y|Ỷ|Ỹ/g, "Y");
  str = str.replace(/Đ/g, "D");
  return str;
}

module.exports = PdfReportStrategy;
